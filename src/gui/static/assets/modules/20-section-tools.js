import { runReaderTask, readerAwait, readerFetch, announce } from "../reader-lifecycle.js";
import { CCGui } from "../gui-runtime.js";
import { apiFetch } from "./10-core.js";
const summaryCache = new Map();
// 20-section-tools.js — per-section tools: permalink, bookmarks, markdown export, summarize.
    // ── Permalink ──
    function copyPermalink(guid, button) {
      const url = `${window.location.origin}/?section=${guid}`;
      if (!navigator.clipboard?.writeText) { announce('Clipboard access is unavailable in this browser context.'); return; }
      navigator.clipboard.writeText(url).then(() => {
        const btn = button;
        const orig = btn.textContent;
        btn.textContent = '✅ Copied!';
        setTimeout(() => btn.textContent = orig, 2000);
      }).catch(() => announce('The browser could not copy this permalink.'));

    }

    // ── Bookmarks ──
    function toggleBookmark(guid, number, title) {
      const bookmarks = CCGui.storage.json("cc-bookmarks", []);
      const idx = bookmarks.findIndex(b => b.guid === guid);
      if (idx >= 0) {
        bookmarks.splice(idx, 1);
      } else {
        bookmarks.push({ guid, number, title, ts: new Date().toISOString() });
      }
      if (!CCGui.storage.set("cc-bookmarks", JSON.stringify(bookmarks))) { announce('Browser storage is unavailable; this bookmark was not saved.'); return; }
      const btn = document.getElementById("bookmark-btn");
      if (btn) btn.textContent = idx >= 0 ? '☆ Bookmark' : '★ Bookmarked';
    }

    function getBookmarks() {
      return CCGui.storage.json("cc-bookmarks", []);
    }

    // ── Export section as Markdown ──
    async function exportSection(guid) { return runReaderTask(`export-${guid}`, async signal => {
      try {
        const resp = await readerAwait(readerFetch(apiFetch, signal, `/api/section/${guid}`), signal);
        if (!resp.ok) throw new Error('The section could not be downloaded.');
        const section = await readerAwait(resp.json(), signal);
        const md = `# § ${section.number}: ${section.title}\n\n` +
          `**Article**: ${section.articleTitle || 'N/A'}\n` +
          `**GUID**: ${guid}\n\n` +
          `## Text\n\n${section.text}\n\n` +
          (section.history ? `## Legislative History\n\n${section.history}\n` : '');
        const blob = new Blob([md], { type: 'text/markdown' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `section-${section.number.replace(/§\s*/, '').replace(/\./g, '-')}.md`;
        a.click();
        URL.revokeObjectURL(url);
        document.getElementById(`export-${guid}`).textContent = 'Markdown download requested.';
      } catch (err) {
        if (signal.aborted) return;
        throw err;
      }
    }); }

    function escapeHtml(str) { return CCGui.escape(str); }

    /** Summarize a section using the configured chat provider via /api/summarize */
    async function summarizeSection(guid, btnEl) { return runReaderTask(`summary-${guid}`, async signal => {
      const targetEl = document.getElementById(`summary-${guid}`);
      if (!targetEl) return;

      // If already cached, display it
      if (summaryCache.has(guid)) {
        const cached = summaryCache.get(guid);
        CCGui.render(targetEl, `<div class="summary-box"><h4>✨ AI Summary</h4>${escapeHtml(cached.summary)}<div class="summary-model">Generated by ${escapeHtml(cached.model)}</div></div>`);
        return;
      }

      // Get the section text from the DOM
      const sectionEl = btnEl.closest('.article-section') || btnEl.closest('.section-body');
      const textEl = sectionEl ? sectionEl.querySelector('.section-text') : null;
      const sectionText = textEl ? textEl.innerText : '';
      const sectionNumber = btnEl.dataset.number || '';
      const sectionTitle = btnEl.dataset.title || '';

      if (!sectionText.trim()) {
        CCGui.render(targetEl, '<div class="summary-box"><h4>⚠️ No Text</h4>This section has no text content to summarize.</div>');
        return;
      }

      // Show loading
      btnEl.disabled = true;
      CCGui.render(targetEl, '<div class="summary-loading">Generating summary with the configured provider...</div>');

      try {
        const resp = await readerFetch(apiFetch, signal, '/api/summarize', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            text: sectionText.substring(0, 8000), // Limit to 8K chars
            number: sectionNumber,
            title: sectionTitle,
          }),
        });
        const data = await readerAwait(resp.json(), signal);
        if (data.error) throw new Error(data.error);

        summaryCache.set(guid, data);
        CCGui.render(targetEl, `<div class="summary-box"><h4>✨ AI Summary</h4>${escapeHtml(data.summary)}<div class="summary-model">Generated by ${escapeHtml(data.model)}</div></div>`);
      } catch (err) {
        if (signal.aborted) return;
        CCGui.render(targetEl, `<div class="summary-box"><h4>❌ Error</h4>${escapeHtml(err.message)}</div>`);
      } finally {
        btnEl.disabled = false;
      }
    }); }

export { copyPermalink, escapeHtml, exportSection, summarizeSection, toggleBookmark };
