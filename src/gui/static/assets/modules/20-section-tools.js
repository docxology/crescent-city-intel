    // ── Permalink ──
    function copyPermalink(guid) {
      const url = `${window.location.origin}/?section=${guid}`;
      navigator.clipboard.writeText(url).then(() => {
        const btn = event.target;
        const orig = btn.textContent;
        btn.textContent = '✅ Copied!';
        setTimeout(() => btn.textContent = orig, 2000);
      });
    }

    // ── Bookmarks ──
    function toggleBookmark(guid, number, title) {
      const bookmarks = JSON.parse(localStorage.getItem("cc-bookmarks") || "[]");
      const idx = bookmarks.findIndex(b => b.guid === guid);
      if (idx >= 0) {
        bookmarks.splice(idx, 1);
      } else {
        bookmarks.push({ guid, number, title, ts: new Date().toISOString() });
      }
      localStorage.setItem("cc-bookmarks", JSON.stringify(bookmarks));
      const btn = document.getElementById("bookmark-btn");
      if (btn) btn.textContent = idx >= 0 ? '☆ Bookmark' : '★ Bookmarked';
    }

    function getBookmarks() {
      return JSON.parse(localStorage.getItem("cc-bookmarks") || "[]");
    }

    // ── Export section as Markdown ──
    async function exportSection(guid) {
      try {
        const resp = await apiFetch(`/api/section/${guid}`);
        const section = await resp.json();
        const md = `# § ${section.number}: ${section.title}\n\n` +
          `**Article**: ${section.articleTitle || 'N/A'}\n` +
          `**GUID**: ${guid}\n\n` +
          `## Text\n\n${section.text}\n\n` +
          (section.history ? `## Legislative History\n\n${section.history}\n` : '');
        const blob = new Blob([md], { type: 'text/markdown' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `section-${section.number.replace(/§\s*/, '').replace(/\./g, '-')}.md`;
        a.click();
        URL.revokeObjectURL(url);
      } catch (err) {
        alert('Export failed: ' + err.message);
      }
    }

    function escapeHtml(str) {
      if (!str) return "";
      return str.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
        .replace(/\n/g, "<br>");
    }

    /** Summarize a section using the configured chat provider via /api/summarize */
    async function summarizeSection(guid, btnEl) {
      const targetEl = document.getElementById(`summary-${guid}`);
      if (!targetEl) return;

      // If already cached, display it
      if (summaryCache.has(guid)) {
        const cached = summaryCache.get(guid);
        targetEl.innerHTML = `<div class="summary-box"><h4>✨ AI Summary</h4>${escapeHtml(cached.summary)}<div class="summary-model">Generated by ${escapeHtml(cached.model)}</div></div>`;
        return;
      }

      // Get the section text from the DOM
      const sectionEl = btnEl.closest('.article-section') || btnEl.closest('.section-body');
      const textEl = sectionEl ? sectionEl.querySelector('.section-text') : null;
      const sectionText = textEl ? textEl.innerText : '';
      const sectionNumber = btnEl.dataset.number || '';
      const sectionTitle = btnEl.dataset.title || '';

      if (!sectionText.trim()) {
        targetEl.innerHTML = '<div class="summary-box"><h4>⚠️ No Text</h4>This section has no text content to summarize.</div>';
        return;
      }

      // Show loading
      btnEl.disabled = true;
      targetEl.innerHTML = '<div class="summary-loading">Generating summary with the configured provider...</div>';

      try {
        const resp = await apiFetch('/api/summarize', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            guid,
            text: sectionText.substring(0, 8000), // Limit to 8K chars
            number: sectionNumber,
            title: sectionTitle,
          }),
        });
        const data = await resp.json();
        if (data.error) throw new Error(data.error);

        summaryCache.set(guid, data);
        targetEl.innerHTML = `<div class="summary-box"><h4>✨ AI Summary</h4>${escapeHtml(data.summary)}<div class="summary-model">Generated by ${escapeHtml(data.model)}</div></div>`;
      } catch (err) {
        targetEl.innerHTML = `<div class="summary-box"><h4>❌ Error</h4>${escapeHtml(err.message)}</div>`;
      } finally {
        btnEl.disabled = false;
      }
    }
